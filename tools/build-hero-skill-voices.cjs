/* Build immutable display names and a manifest-backed audio allowlist. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createHash } = require('node:crypto');
const root = path.resolve(__dirname, '..');
const source = path.join(root, 'art-source/audio/voice-hero-skills-v1');
const target = path.join(root, 'hero-skill-voices.js');
const script = JSON.parse(fs.readFileSync(path.join(root, 'docs/CULTIVATION_HERO_VOICE_SCRIPT.json'), 'utf8'));
const contract = JSON.parse(fs.readFileSync(path.join(source, 'contract.json'), 'utf8'));
const digest = data => createHash('sha256').update(data).digest('hex');
assert.equal(script.status, 'text-approved');
assert.equal(digest(JSON.stringify(script.heroes)), script.approval.heroesSha256);
assert.equal(contract.sourceContentSha256, script.approval.heroesSha256);
const skills = new Map(require('../cultivation-skills.js').all.map(skill => [skill.id, skill]));
const all = script.heroes.map(hero => {
  const production = contract.heroes.find(item => item.heroId === hero.heroId);
  assert.ok(production, 'Missing production hero: ' + hero.heroId);
  const expected = new Map(production.batches.flatMap(batch => batch.lines.map(line => [line.id, { ...line, batchId: batch.id }])));
  const manifestPath = path.join(source, hero.heroId, 'manifest.json');
  const manifest = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, 'utf8')) : null;
  const clips = new Map();
  if (manifest) {
    assert.equal(manifest.heroId, hero.heroId);
    assert.equal(manifest.voiceId, production.voiceId);
    assert.equal(manifest.processed_count, manifest.clips.length);
    for (const clip of manifest.clips) {
      const line = expected.get(clip.id);
      assert.ok(line && !clips.has(clip.id), 'Unexpected or duplicate clip: ' + clip.id);
      for (const key of ['text', 'direction', 'taggedText', 'batchId']) assert.equal(clip[key], line[key], hero.heroId + '/' + clip.id + ' outdated ' + key);
      const file = 'assets/audio/voice-hero-skills-v1/' + hero.heroId + '/' + clip.id.replace(/:/g, '--') + '.mp3';
      assert.equal(clip.file, file);
      assert.equal(digest(fs.readFileSync(path.join(root, file))), clip.sha256, file + ' hash mismatch');
      assert.ok(Number.isFinite(clip.levels.duration_seconds) && clip.levels.duration_seconds > 0);
      clips.set(clip.id, clip);
    }
  }
  const lines = [
    ...hero.lines.map(line => ({ id: line.skillId, name: line.name, text: line.reading, action: line.skillId.startsWith('finisher:') ? 'finish' : skills.get(line.skillId)?.action })),
    ...hero.calls.map(line => ({ id: 'call:' + line.cue, name: line.text.replace(/[。！？]+$/u, ''), text: line.text, action: 'call' })),
  ].map(line => {
    assert.equal(expected.get(line.id)?.text, line.text, hero.heroId + '/' + line.id + ' text differs');
    assert.ok(line.action);
    const clip = clips.get(line.id);
    return { ...line, file: clip?.file || null, durationSeconds: clip?.levels.duration_seconds || null };
  });
  assert.equal(lines.length, 213);
  return { heroId: hero.heroId, name: hero.name, lines };
});
assert.equal(all.length, 10);
const payload = JSON.stringify(all).replace(/</g, '\\u003c');
const output = `/* Generated by tools/build-hero-skill-voices.cjs. Names never change combat or saves. */
(function (root) {
  'use strict';
  const all = ${payload};
  const heroes = new Map();
  for (const hero of all) {
    hero.lines = Object.freeze(hero.lines.map(line => Object.freeze({ ...line, heroId: hero.heroId, reading: line.text })));
    heroes.set(hero.heroId, new Map(hero.lines.map(line => [line.id, line])));
    Object.freeze(hero);
  }
  const aliases = new Map([['formation.seven', 'finisher:seven'], ['formation.eight', 'finisher:eight']]);
  function get(heroId, skillId, options) {
    // Privacy is resolved before looking at any private skill identifier.
    const id = options?.secret === true ? 'call:concealed' : aliases.get(skillId) || skillId;
    return heroes.get(heroId)?.get(id) || null;
  }
  function onEffect(effect, before) {
    if (!effect || !['skill', 'finisherPart'].includes(effect.type)) return null;
    const heroId = before?.players?.[effect.pid]?.heroId;
    if (effect.secret === true) return get(heroId, null, { secret: true });
    return get(heroId, effect.type === 'finisherPart' ? 'finisher:' + effect.segmentId : effect.skillId);
  }
  const api = Object.freeze({ all: Object.freeze(all), get, onEffect,
    name: (heroId, skillId, options) => get(heroId, skillId, options)?.name || null,
    contentSha256: '${script.approval.heroesSha256}' });
  root.MahjongHeroSkillVoices = api;
  if (typeof module === 'object' && module.exports) module.exports = api;
})(typeof window === 'object' ? window : globalThis);
`;
const mode = process.argv[2] || '--write';
assert.ok(['--write', '--check'].includes(mode));
if (mode === '--check') assert.equal(fs.readFileSync(target, 'utf8'), output, 'Registry is out of date; run --write');
else if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
  if (fs.existsSync(target)) {
    const folder = path.join(root, '.local-backups/hero-skill-voices');
    fs.mkdirSync(folder, { recursive: true });
    fs.copyFileSync(target, path.join(folder, 'hero-skill-voices.js.bak.' + new Date().toISOString().replace(/[:.]/g, '-')), fs.constants.COPYFILE_EXCL);
  }
  fs.writeFileSync(target, output, 'utf8');
}
console.log(JSON.stringify({ status: 'passed', mode, names: 2050, calls: 80, availableAudio: all.flatMap(hero => hero.lines).filter(line => line.file).length }));
