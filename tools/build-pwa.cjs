// Run after changing the app shell so installed apps receive a new cache version.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.join(__dirname, '..');
const files = fs.readdirSync(root).filter(file => /\.(css|js)$/.test(file)
  && !['sw.js', 'pwa-assets.js'].includes(file));
files.push('index.html', 'manifest.webmanifest', 'assets/pwa/icon-192.png',
  'assets/pwa/icon-512.png', 'assets/pwa/apple-touch-icon.png');
files.sort();
const hash = crypto.createHash('sha256');
for (const file of [...files, 'sw.js']) {
  const content = fs.readFileSync(path.join(root, file));
  // Git may check text out as CRLF on Windows; the release hash must be portable.
  hash.update(file).update(/\.(html|css|js|webmanifest)$/.test(file)
    ? content.toString('utf8').replace(/\r\n/g, '\n') : content);
}
const output = '// Generated by node tools/build-pwa.cjs; do not edit by hand.\n'
  + 'self.MAHJONG_PRECACHE = ' + JSON.stringify({ version: hash.digest('hex').slice(0, 16), urls: files }, null, 2) + ';\n';
const target = path.join(root, 'pwa-assets.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
    console.error('PWA cache manifest is stale. Run node tools/build-pwa.cjs.');
    process.exitCode = 1;
  } else console.log(`PWA cache manifest current: ${files.length} files.`);
} else {
  fs.writeFileSync(target, output);
  console.log(`Generated PWA cache manifest: ${files.length} files.`);
}
